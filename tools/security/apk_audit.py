#!/usr/bin/env python3
"""Static security + branding audit of a built Swiftra APK (no device needed).

Checks (each PASS/FAIL, final line APK_AUDIT PASS|FAIL):
  manifest   android:debuggable not true, android:testOnly not true, android:allowBackup false
  signing    APK Signature Scheme v2 and v3 present; signer certificate SHA-256 == patches/signing_cert_sha256.txt
  exported   components exported without a permission == the upstream baseline (tools/security/exported_baseline.txt):
             a Swiftra patch that adds a new unprotected entry point fails the audit (an upstream rebase that changes
             the list is reviewed and the baseline updated on purpose)
  branding   no drawable/mipmap/raw/font resource named after a Google/Chrome product (logos are trademarks)
  cleartext  network security config recorded (upstream Chrome's: user + system trust anchors, http allowed for
             browsing); reported, not judged

Usage: apk_audit.py --apk ChromePublic.apk [--json out.json] [--write-baseline]
Needs: pip install androguard
"""
import argparse
import hashlib
import json
import logging
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASELINE = os.path.join(ROOT, "tools", "security", "exported_baseline.txt")
CERT_FILE = os.path.join(ROOT, "patches", "signing_cert_sha256.txt")
NS = "{http://schemas.android.com/apk/res/android}"
BRAND = re.compile(r"google|chrome|gmail|youtube|gemini|play_?store|googleg|doodle|assistant", re.I)


def load_apk(path):
    logging.disable(logging.CRITICAL)
    try:
        from loguru import logger
        logger.remove()
    except ImportError:
        pass
    from androguard.core.apk import APK
    return APK(path)


def exported_unprotected(apk):
    app = apk.get_android_manifest_xml().find("application")
    out = []
    for tag in ("activity", "activity-alias", "service", "receiver", "provider"):
        for e in app.findall(tag):
            if e.get(NS + "exported") == "true" and not (e.get(NS + "permission") or e.get(NS + "readPermission")):
                out.append(f"{tag} {e.get(NS + 'name')}")
    return sorted(out)


def brand_images(apk, apk_path):
    res = apk.get_android_resources()
    pkg = res.get_packages_names()[0]
    data = zipfile.ZipFile(apk_path).read("resources.arsc")
    names = {m.decode() for m in re.findall(rb"[a-z][a-z0-9_]{3,80}", data)}
    names |= {m.decode("utf-16le") for m in re.findall(rb"(?:[a-z0-9_]\x00){4,80}", data)}
    hits = []
    for n in sorted(x for x in names if BRAND.search(x)):
        for t in ("drawable", "mipmap", "raw", "font"):
            try:
                if res.get_res_id_by_key(pkg, t, n):
                    hits.append(f"{t}/{n}")
            except Exception:  # noqa: BLE001 - name not of this type
                pass
    return hits, len(names)


def audit(apk_path, write_baseline=False):
    apk = load_apk(apk_path)
    app = apk.get_android_manifest_xml().find("application")
    checks, info = {}, {"package": apk.get_package(), "target_sdk": apk.get_target_sdk_version(),
                        "sha256": hashlib.sha256(open(apk_path, "rb").read()).hexdigest()}
    checks["not_debuggable"] = app.get(NS + "debuggable") != "true"
    checks["not_test_only"] = app.get(NS + "testOnly") != "true"
    checks["allow_backup_false"] = app.get(NS + "allowBackup") == "false"
    checks["signed_v2_v3"] = bool(apk.is_signed_v2() and apk.is_signed_v3())
    certs = [hashlib.sha256(c).hexdigest() for c in (apk.get_certificates_der_v3() or apk.get_certificates_der_v2())]
    want = None
    if os.path.exists(CERT_FILE):                # first 64-hex token outside comment lines
        m = re.search(r"^\s*([0-9a-fA-F]{64})\b", "\n".join(l for l in open(CERT_FILE) if not l.lstrip().startswith("#")),
                      re.M)
        want = m.group(1).lower() if m else None
    info["signer_cert_sha256"] = certs
    checks["signer_cert_expected"] = bool(want) and certs == [want]
    exp = exported_unprotected(apk)
    info["exported_unprotected"] = len(exp)
    if write_baseline:
        with open(BASELINE, "w") as f:
            f.write("# Components exported without a permission in upstream Chromium 155 ChromePublic (no Swiftra patch\n"
                    "# adds android:exported). Generated by tools/security/apk_audit.py --write-baseline.\n")
            f.write("\n".join(exp) + "\n")
    base = [l.strip() for l in open(BASELINE) if l.strip() and not l.startswith("#")] if os.path.exists(BASELINE) else []
    info["exported_new"] = sorted(set(exp) - set(base))
    info["exported_gone"] = sorted(set(base) - set(exp))
    checks["no_new_exported_entry_points"] = bool(base) and not info["exported_new"]
    imgs, nnames = brand_images(apk, apk_path)
    info["brand_images"], info["resource_names_scanned"] = imgs, nnames
    checks["no_google_chrome_logo_images"] = not imgs
    nsc = app.get(NS + "networkSecurityConfig")
    info["network_security_config"] = nsc
    return checks, info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apk", required=True)
    ap.add_argument("--json")
    ap.add_argument("--write-baseline", action="store_true")
    a = ap.parse_args()
    try:
        checks, info = audit(a.apk, a.write_baseline)
    except ImportError:
        print("APK_AUDIT NOT_RUN androguard missing (pip install androguard)")
        return 0
    for k, v in checks.items():
        print(f"{'PASS' if v else 'FAIL'}  {k}")
    for k in ("package", "target_sdk", "sha256", "signer_cert_sha256", "exported_unprotected", "exported_new",
              "exported_gone", "brand_images", "resource_names_scanned", "network_security_config"):
        print(f"      {k}: {info[k]}")
    if a.json:
        json.dump({"checks": checks, "info": info}, open(a.json, "w"), indent=1)
    ok = all(checks.values())
    print(f"APK_AUDIT {'PASS' if ok else 'FAIL'} {sum(checks.values())}/{len(checks)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
